import { build } from 'esbuild';
import fs from 'node:fs/promises';

const pkg = JSON.parse(await fs.readFile('package.json', 'utf8'));
if (!pkg.userscript?.name || !pkg.userscript?.description || !/^\d+\.\d+\.\d+$/.test(pkg.version || '')) {
  throw new Error('package.json must define userscript name/description and a numeric semantic version');
}

const retailers = [
  {
    label: 'Real Canadian Superstore and No Frills (Loblaw / PC Express)',
    test: "hostname === 'www.realcanadiansuperstore.ca' || hostname === 'www.nofrills.ca'",
    entry: 'src/retailers/loblaw/plugin.js'
  },
  {
    label: 'Walmart Canada',
    test: "hostname === 'www.walmart.ca'",
    entry: 'src/retailers/walmart/userscript-main.js'
  },
  {
    label: 'Save-On-Foods',
    test: "hostname === 'www.saveonfoods.com'",
    entry: 'src/retailers/saveon/plugin.js'
  }
];

async function bundle(entry) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    target: ['safari18'],
    // Preserve `/*! ... */` architecture notes in the installed userscript.
    // They add file bytes but no executed work, so UI/runtime speed is unchanged.
    legalComments: 'inline',
    minify: false,
    write: false
  });
  return result.outputFiles[0].text.trim();
}

const branches = [];
for (const retailer of retailers) {
  const source = `  /* Plugin entry: ${retailer.entry}\n   * Capture installs before the retailer runtime through the formal plugin contract.\n   */\n${await bundle(retailer.entry)}`;
  branches.push(`/* ==========================================================================\n * Retailer adapter: ${retailer.label}\n * Only this hostname branch runs; the other retailer bundles stay inert.\n * ========================================================================== */\nif (${retailer.test}) {\n${source}\n}`);
}

const metadata = `// ==UserScript==
// @name        ${pkg.userscript.name}
// @version     ${pkg.version}
// @description ${pkg.userscript.description}
// @downloadURL https://github.com/nabekhan/grocery-price-per-unit/releases/latest/download/Grocery-Price-Per-Unit.user.js
// @updateURL   https://github.com/nabekhan/grocery-price-per-unit/releases/latest/download/Grocery-Price-Per-Unit.user.js
// @match       https://www.realcanadiansuperstore.ca/*
// @match       https://www.nofrills.ca/*
// @match       https://www.walmart.ca/*
// @match       https://www.saveonfoods.com/*
// @run-at      document-start
// @inject-into page
// @weight      999
// @grant       none
// @noframes
// ==/UserScript==`;

const architectureNotes = `/*
 * Grocery Price Per Unit — generated, readable userscript
 *
 * Architecture
 * 1. One exact-host retailer plugin installs its capture phase before its UI
 *    phase; the generated artifact remains one userscript.
 * 2. A page-world response observer accepts only each retailer's own bounded
 *    product records. Product facts are never reconstructed from card text.
 * 3. Retailer adapters match accepted product IDs to rendered result cards.
 * 4. The parser normalizes mass, volume, and count independently; unlike
 *    dimensions are never ranked against one another.
 * 5. The sorter owns only its annotations, inline order values, and narrowly
 *    recognized sponsored/ad visibility. Restore releases that ownership.
 * 6. The fixed control reports pending/no-match states instead of presenting a
 *    stale sort as current. Missed capture offers only a user-operated reload;
 *    cookie prompts and CAPTCHAs remain human-only.
 *
 * Source of truth
 * This file is generated by scripts/build-userscript.mjs from src/. Edit the
 * source modules, then rebuild; do not hand-edit the installed artifact.
 */`;

const storageShim = `
  /* ------------------------------------------------------------------------
   * Minimal preference storage
   *
   * Retailer adapters share a deliberately small asynchronous storage contract.
   * This page-world implementation provides it over origin-local
   * storage, with an in-memory fallback when Safari denies or exhausts it.
   * ---------------------------------------------------------------------- */
  const storagePrefix = '__gppu_userscript_storage__:';
  const storageListeners = new Set();
  const storageMemory = new Map();
  const storageCapabilityKey = Symbol.for('grocery-price-per-unit.storage.v1');

  const physicalKey = (area, key) => storagePrefix + area + ':' + key;
  const keysFor = (area) => {
    const prefix = storagePrefix + area + ':';
    const result = new Set([...storageMemory.keys()].filter((key) => key.startsWith(prefix)).map((key) => key.slice(prefix.length)));
    try {
      for (let index = 0; index < localStorage.length; index += 1) {
        const key = localStorage.key(index);
        if (key?.startsWith(prefix)) result.add(key.slice(prefix.length));
      }
    } catch { /* Safari can deny origin storage. */ }
    return [...result];
  };
  const read = (area, key) => {
    const target = physicalKey(area, key);
    if (storageMemory.has(target)) {
      try { return JSON.parse(storageMemory.get(target)); } catch { return undefined; }
    }
    let value = null;
    try { value = localStorage.getItem(target); } catch { /* use the in-memory mirror */ }
    if (value == null) return undefined;
    try { return JSON.parse(value); } catch { return undefined; }
  };
  const write = (area, key, value) => {
    const target = physicalKey(area, key);
    const serialized = JSON.stringify(value);
    storageMemory.set(target, serialized);
    try { localStorage.setItem(target, serialized); } catch { /* memory remains authoritative for this page */ }
  };
  const remove = (area, key) => {
    const target = physicalKey(area, key);
    storageMemory.delete(target);
    try { localStorage.removeItem(target); } catch { /* memory is already clear */ }
  };
  const returnWithCallback = (promise, callback) => {
    if (typeof callback !== 'function') return promise;
    promise.then((value) => { try { callback(value); } catch { /* isolate page listeners */ } }, () => {
      try { callback(undefined); } catch { /* isolate page listeners */ }
    });
    return undefined;
  };
  const makeArea = (area) => ({
    get(keys, callback) {
      const operation = Promise.resolve().then(() => {
        if (keys == null) return Object.fromEntries(keysFor(area).map((key) => [key, read(area, key)]));
        const defaults = keys && typeof keys === 'object' && !Array.isArray(keys) ? keys : {};
        const requested = typeof keys === 'string' ? [keys] : Array.isArray(keys) ? keys : Object.keys(defaults);
        return Object.fromEntries(requested.map((key) => [key, read(area, key) ?? defaults[key]]));
      });
      return returnWithCallback(operation, callback);
    },
    set(items, callback) {
      const operation = Promise.resolve().then(() => {
        const changes = {};
        for (const [key, newValue] of Object.entries(items || {})) {
          const oldValue = read(area, key);
          write(area, key, newValue);
          if (JSON.stringify(oldValue) !== JSON.stringify(newValue)) changes[key] = { oldValue, newValue };
        }
        if (Object.keys(changes).length) for (const listener of storageListeners) {
          try { listener(changes, area); } catch { /* one listener cannot break the adapter */ }
        }
      });
      return returnWithCallback(operation, callback);
    },
    remove(keys, callback) {
      const operation = Promise.resolve().then(() => {
        for (const key of typeof keys === 'string' ? [keys] : keys || []) remove(area, key);
      });
      return returnWithCallback(operation, callback);
    },
    clear(callback) {
      const operation = Promise.resolve().then(() => {
        for (const key of keysFor(area)) remove(area, key);
      });
      return returnWithCallback(operation, callback);
    }
  });

  if (!globalThis[storageCapabilityKey]?.storage) {
    const storage = {
      local: makeArea('local'),
      sync: makeArea('sync'),
      onChanged: {
        addListener(listener) { storageListeners.add(listener); },
        removeListener(listener) { storageListeners.delete(listener); },
        hasListener(listener) { return storageListeners.has(listener); }
      }
    };
    Object.defineProperty(globalThis, storageCapabilityKey, {
      configurable: false,
      enumerable: false,
      value: Object.freeze({ storage })
    });
  }
  const userscriptStorage = globalThis[storageCapabilityKey].storage;
`;

const output = `${metadata}\n\n${architectureNotes}\n\n(() => {
  'use strict';

  /* Prevent duplicate installation when Safari or a script manager evaluates
   * the file more than once in the same page world. */
  const userscriptInstallKey = Symbol.for('grocery-price-per-unit.userscript-install.v1');
  try {
    if (globalThis[userscriptInstallKey]) return;
    Object.defineProperty(globalThis, userscriptInstallKey, {
      configurable: false,
      enumerable: false,
      value: true
    });
  } catch {
    return;
  }
${storageShim}
  /* Host routing is deliberately exact: supported adapters never run on an
   * unrelated origin, even if a script manager grants broader access. */
  const hostname = window.location.hostname;
  ${branches.join(' else ')}

  /* The selected mode affects only the current page until the shopper explicitly
   * chooses “Use as default”. The namespaced local preference is deliberately
   * scoped to each retailer origin; unrelated sites cannot read it. */
  document.addEventListener('gppu:default-change', (event) => {
    const value = event.detail?.value;
    if (!/^(restore|(auto|mass|volume|count|total)-(asc|desc))$/.test(value || '')) return;
    write('sync', 'defaultSortMode', value);
  });
})();\n`;

// A userscript-only build cannot leave a stale extension tree looking current.
await fs.rm('dist', { recursive: true, force: true });
await fs.mkdir('dist/userscript', { recursive: true });
await fs.writeFile('dist/userscript/Grocery Price Per Unit.user.js', output);
